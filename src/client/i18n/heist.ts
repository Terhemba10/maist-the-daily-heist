export const LANGS = { en: 'English', zh: '中文', ja: '日本語', de: 'Deutsch', hi: 'हिन्दी' } as const;
export type Lang = keyof typeof LANGS;
const DICTS: Record<Lang, Dict> = { en, zh, ja, de, hi };

const KEY = 'heist.lang';
function detect(): Lang {
  try {
    const saved = window.localStorage.getItem(KEY);
    if (saved && saved in LANGS) return saved as Lang;
  } catch {
    /* storage can be blocked */
  }
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return nav in LANGS ? (nav as Lang) : 'en';
}

let lang: Lang = detect();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
  try {
    window.localStorage.setItem(KEY, l);
  } catch {
    /* ignore */
  }
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
